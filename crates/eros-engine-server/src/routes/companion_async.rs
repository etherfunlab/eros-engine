/// Per-turn request knobs snapshotted into `chat_turn_queue.params` at
/// enqueue time and replayed by the worker at generation time. Field-for-field
/// the optional tail of `StreamSendRequest`.
#[derive(Debug, Default, Serialize, Deserialize)]
pub(crate) struct QueuedTurnParams {
    #[serde(default)]
    pub tier: Option<String>,
    #[serde(default)]
    pub memory_scope: Option<MemoryScope>,
    #[serde(default)]
    pub affinity_scope: Option<AffinityScopeDto>,
    #[serde(default)]
    pub prompt_traits: Option<Vec<PromptTraitDto>>,
    #[serde(default)]
    pub audit: Option<LlmAuditDto>,
    #[serde(default)]
    pub tips_amount_usd: Option<f64>,
    #[serde(default)]
    pub image_url: Option<String>,
    #[serde(default)]
    pub image: Option<ImageReplyParams>,
    #[serde(default)]
    pub reply_to_message_id: Option<Uuid>,
}

#[derive(Debug, Serialize, utoipa::ToSchema)]
pub struct AsyncSendResponse {
    /// `queued` | `already_queued` | `already_completed` | `failed`
    pub status: String,
    #[schema(value_type = String)]
    pub user_message_id: Uuid,
}

/// Enqueue a chat turn for asynchronous delivery.
///
/// Validates and persists the user message, then hands the turn to a
/// background worker; the assistant reply is generated out-of-band and lands
/// in this session's history over whatever channel the client already polls
/// or subscribes to (SSE / GET history) — this endpoint itself never returns
/// reply content. Idempotent on `client_msg_id`: redelivering a turn that is
/// already queued, completed, or terminally failed returns that outcome
/// instead of enqueueing a duplicate.
#[utoipa::path(
    post,
    path = "/v2/comp/session/{session_id}/message/async",
    tag = "companion",
    params(("session_id" = Uuid, Path, description = "Chat session id")),
    request_body = StreamSendRequest,
    responses(
        (status = 202, description = "Turn enqueued (`queued`) or an idempotent \
            redelivery of a turn still being handled (`already_queued`). The reply \
            is generated by a background worker and lands in this session's \
            history; no reply content is ever returned here.", body = AsyncSendResponse),
        (status = 200, description = "Idempotent replay: this client_msg_id was \
            already processed (`already_completed`) or terminally failed \
            (`failed`).", body = AsyncSendResponse),
        (status = 400, body = StreamPreErrorBody),
        (status = 401, description = "missing or invalid bearer"),
        (status = 403, body = StreamPreErrorBody),
        (status = 404, body = StreamPreErrorBody),
        (status = 409, body = StreamPreErrorBody),
        (status = 422, body = StreamPreErrorBody),
        (status = 429, body = StreamPreErrorBody),
    ),
    security(("bearer" = []))
)]
pub async fn send_message_async(
    State(state): State<AppState>,
    Path(session_id): Path<Uuid>,
    Extension(AuthUser(user_id)): Extension<AuthUser>,
    Json(req): Json<StreamSendRequest>,
) -> Result<(StatusCode, Json<AsyncSendResponse>), AppError> {
    validate_payload(&req)?;
    validate_image_capability(&req, &state.model_config)?;
    // Validate now so a bad request 400s at enqueue, not silently in the
    // worker; the raw DTOs (not the validated outputs) go into params and the
    // worker re-runs these same pure fns.
    validate_prompt_traits(req.prompt_traits.as_deref().unwrap_or(&[])).map_err(|e| {
        AppError::StreamPre(StreamPreError {
            status: StatusCode::BAD_REQUEST,
            code: "invalid_payload",
            message: e.to_string(),
            user_message: "请求无效".into(),
            original_user_message_id: None,
        })
    })?;
    validate_llm_audit(req.audit.clone()).map_err(|e| {
        AppError::StreamPre(StreamPreError {
            status: StatusCode::BAD_REQUEST,
            code: "invalid_payload",
            message: e.to_string(),
            user_message: "请求无效".into(),
            original_user_message_id: None,
        })
    })?;

    let (_session, _persona, _instance_id) = resolve_text_turn(&state, session_id, user_id).await?;

    let chat_repo = ChatRepo { pool: &state.pool };
    let quote = resolve_quote(&chat_repo, session_id, req.reply_to_message_id).await?;
    let persisted_metadata = build_user_row_metadata(&req, quote.as_ref());
    let (persisted_content, persisted_role) = persisted_content_role(&req);

    let params = serde_json::to_value(QueuedTurnParams {
        tier: req.tier.clone(),
        memory_scope: req.memory_scope,
        affinity_scope: req.affinity_scope,
        prompt_traits: req.prompt_traits,
        audit: req.audit,
        tips_amount_usd: req.tips_amount_usd,
        image_url: req.image_url,
        image: req.image,
        reply_to_message_id: req.reply_to_message_id,
    })
    .expect("QueuedTurnParams serializes");

    let queue_repo = ChatQueueRepo { pool: &state.pool };
    let outcome = queue_repo
        .enqueue_user_message(
            session_id,
            &persisted_content,
            &req.client_msg_id,
            persisted_role,
            persisted_metadata.as_ref(),
            user_id,
            &params,
            state.config.chat_queue.pending_cap,
        )
        .await?;

    let (status, body) = match outcome {
        EnqueueOutcome::Queued {
            user_message_id, ..
        } => {
            state.chat_queue_notify.notify_one();
            (
                StatusCode::ACCEPTED,
                AsyncSendResponse {
                    status: "queued".into(),
                    user_message_id,
                },
            )
        }
        EnqueueOutcome::AlreadyQueued { user_message_id } => (
            StatusCode::ACCEPTED,
            AsyncSendResponse {
                status: "already_queued".into(),
                user_message_id,
            },
        ),
        EnqueueOutcome::AlreadyCompleted { user_message_id } => (
            StatusCode::OK,
            AsyncSendResponse {
                status: "already_completed".into(),
                user_message_id,
            },
        ),
        EnqueueOutcome::Failed { user_message_id } => (
            StatusCode::OK,
            AsyncSendResponse {
                status: "failed".into(),
                user_message_id,
            },
        ),
        EnqueueOutcome::DepthExceeded => {
            return Err(AppError::StreamPre(StreamPreError {
                status: StatusCode::TOO_MANY_REQUESTS,
                code: "rate_limited",
                message: format!(
                    "per-session pending cap reached ({})",
                    state.config.chat_queue.pending_cap
                ),
                user_message: "请求过多，请稍后再试".into(),
                original_user_message_id: None,
            }));
        }
    };
    Ok((status, Json(body)))
}

pub fn router() -> OpenApiRouter<AppState> {
    OpenApiRouter::new().routes(routes!(send_message_async))
}

