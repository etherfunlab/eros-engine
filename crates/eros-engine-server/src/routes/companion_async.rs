    async fn post_json(
        app: &mut Router,
        uri: &str,
        token: &str,
        body: Value,
    ) -> (StatusCode, Value) {
        let req = Request::builder()
            .method("POST")
            .uri(uri)
            .header(header::AUTHORIZATION, format!("Bearer {token}"))
            .header(header::CONTENT_TYPE, "application/json")
            .body(Body::from(serde_json::to_vec(&body).unwrap()))
            .unwrap();
        let resp = app.call(req).await.unwrap();
        let status = resp.status();
        let bytes = to_bytes(resp.into_body(), 1024 * 1024).await.unwrap();
        let v: Value = if bytes.is_empty() {
            Value::Null
        } else {
            serde_json::from_slice(&bytes).unwrap()
        };
        (status, v)
    }

    // Test 1: fresh enqueue → 202 {"status":"queued"}, user row + pending
    // queue row exist.
    #[sqlx::test(migrations = "../eros-engine-store/migrations")]
    async fn async_202_queued_on_fresh_enqueue(pool: PgPool) {
        let user_id = Uuid::new_v4();
        let genome_id = seed_genome(&pool, "Aria").await;
        let instance_id = seed_instance(&pool, genome_id, user_id).await;
        let session_id = seed_session(&pool, user_id, instance_id).await;

        let mut app = build_router(test_state(pool.clone()));
        let token = mint_test_jwt(user_id);

        let (status, body) = post_json(
            &mut app,
            &async_uri(session_id),
            &token,
            json!({"content":"hi","client_msg_id":"01JV000000000000000000001A"}),
        )
        .await;
        assert_eq!(status, StatusCode::ACCEPTED, "body: {body}");
        assert_eq!(body["status"], "queued");
        let user_message_id =
            Uuid::parse_str(body["user_message_id"].as_str().expect("uuid string"))
                .expect("user_message_id is a valid uuid");

        let pending: i64 = sqlx::query_scalar(
            "SELECT count(*) FROM engine.chat_turn_queue WHERE session_id = $1 AND status = 'pending'",
        )
        .bind(session_id)
        .fetch_one(&pool)
        .await
        .unwrap();
        assert_eq!(pending, 1);

        let content: String =
            sqlx::query_scalar("SELECT content FROM engine.chat_messages WHERE id = $1")
                .bind(user_message_id)
                .fetch_one(&pool)
                .await
                .unwrap();
        assert_eq!(content, "hi");
    }

    // Test 2: redelivery of the same client_msg_id → 202
    // {"status":"already_queued"}, still one queue row.
    #[sqlx::test(migrations = "../eros-engine-store/migrations")]
    async fn async_202_already_queued_on_redelivery(pool: PgPool) {
        let user_id = Uuid::new_v4();
        let genome_id = seed_genome(&pool, "Aria").await;
        let instance_id = seed_instance(&pool, genome_id, user_id).await;
        let session_id = seed_session(&pool, user_id, instance_id).await;

        let mut app = build_router(test_state(pool.clone()));
        let token = mint_test_jwt(user_id);
        let payload = json!({"content":"hi","client_msg_id":"01JV000000000000000000002A"});

        let (first_status, first_body) =
            post_json(&mut app, &async_uri(session_id), &token, payload.clone()).await;
        assert_eq!(first_status, StatusCode::ACCEPTED, "body: {first_body}");
        assert_eq!(first_body["status"], "queued");

        let (second_status, second_body) =
            post_json(&mut app, &async_uri(session_id), &token, payload).await;
        assert_eq!(second_status, StatusCode::ACCEPTED, "body: {second_body}");
        assert_eq!(second_body["status"], "already_queued");
        assert_eq!(
            second_body["user_message_id"], first_body["user_message_id"],
            "redelivery must resolve to the same persisted user row"
        );

        let pending: i64 = sqlx::query_scalar(
            "SELECT count(*) FROM engine.chat_turn_queue WHERE session_id = $1 AND status = 'pending'",
        )
        .bind(session_id)
        .fetch_one(&pool)
        .await
        .unwrap();
        assert_eq!(pending, 1, "redelivery must not create a second queue row");
    }

    // Test 3: completed replay → 200 {"status":"already_completed"}.
    #[sqlx::test(migrations = "../eros-engine-store/migrations")]
    async fn async_200_already_completed_on_replay(pool: PgPool) {
        use eros_engine_store::chat::{AssistantInsert, ChatRepo, UpsertUserOutcome};

        let user_id = Uuid::new_v4();
        let genome_id = seed_genome(&pool, "Aria").await;
        let instance_id = seed_instance(&pool, genome_id, user_id).await;
        let session_id = seed_session(&pool, user_id, instance_id).await;

        // Pre-seed an already-completed turn: a user row plus an assistant
        // reply chained off it, exactly as the sync stream path would leave
        // behind — the async endpoint must recognise this client_msg_id as
        // already handled rather than re-enqueueing it.
        let chat_repo = ChatRepo { pool: &pool };
        let user_msg_id = match chat_repo
            .upsert_user_message_idempotent(
                session_id,
                "hi",
                "01JV000000000000000000003A",
                "user",
                None,
            )
            .await
            .unwrap()
        {
            UpsertUserOutcome::Inserted { message_id } => message_id,
            _ => unreachable!(),
        };
        // Since 0060 chat_messages.generation_id FK-references
        // engine.llm_generations. Release A's write path creates the parent;
        // this test writes the child row directly, so it seeds one itself.
        sqlx::query(
            "INSERT INTO engine.llm_generations (generation_id, task) \
             VALUES ('gen-1', 'chat_companion')",
        )
        .execute(&pool)
        .await
        .unwrap();
        let assistant_uuid: Uuid = ulid::Ulid::new().into();
        chat_repo
            .insert_assistant_batch(
                session_id,
                user_msg_id,
                &[AssistantInsert {
                    llm_attempts: None,
                    gateway_errors: None,
                    id: assistant_uuid,
                    content: "already replied".into(),
                    assistant_action_type: "reply".into(),
                    continues_from_message_id: None,
                    truncated: false,
                    model: Some("primary".into()),
                    usage: None,
                    generation_id: Some("gen-1".into()),
                    filter_audit: None,
                    metadata: None,
                }],
            )
            .await
            .unwrap();

        let mut app = build_router(test_state(pool.clone()));
        let token = mint_test_jwt(user_id);
        let (status, body) = post_json(
            &mut app,
            &async_uri(session_id),
            &token,
            json!({"content":"hi","client_msg_id":"01JV000000000000000000003A"}),
        )
        .await;
        assert_eq!(status, StatusCode::OK, "body: {body}");
        assert_eq!(body["status"], "already_completed");
        assert_eq!(body["user_message_id"], json!(user_msg_id.to_string()));
    }

    // Test 4: per-session pending cap → the first `pending_cap` distinct
    // turns enqueue (202), the next one 429s {"code":"rate_limited"} and
    // persists no chat_messages row for the rejected client_msg_id.
    #[sqlx::test(migrations = "../eros-engine-store/migrations")]
    async fn async_429_when_pending_cap_reached(pool: PgPool) {
        let user_id = Uuid::new_v4();
        let genome_id = seed_genome(&pool, "Aria").await;
        let instance_id = seed_instance(&pool, genome_id, user_id).await;
        let session_id = seed_session(&pool, user_id, instance_id).await;

        let mut state = test_state(pool.clone());
        state.config.chat_queue.pending_cap = 2;
        let mut app = build_router(state);
        let token = mint_test_jwt(user_id);

        for n in 1..=2 {
            let client_msg_id = format!("01JV00000000000000000001{n}A");
            let (status, body) = post_json(
                &mut app,
                &async_uri(session_id),
                &token,
                json!({"content": format!("turn {n}"), "client_msg_id": client_msg_id}),
            )
            .await;
            assert_eq!(status, StatusCode::ACCEPTED, "turn {n} body: {body}");
            assert_eq!(body["status"], "queued");
        }

        let rejected_client_msg_id = "01JV000000000000000000013A";
        let (status, body) = post_json(
            &mut app,
            &async_uri(session_id),
            &token,
            json!({"content":"one too many","client_msg_id": rejected_client_msg_id}),
        )
        .await;
        assert_eq!(status, StatusCode::TOO_MANY_REQUESTS, "body: {body}");
        assert_eq!(body["code"], "rate_limited");

        let rows: i64 = sqlx::query_scalar(
            "SELECT count(*) FROM engine.chat_messages WHERE session_id = $1 AND client_msg_id = $2",
        )
        .bind(session_id)
        .bind(rejected_client_msg_id)
        .fetch_one(&pool)
        .await
        .unwrap();
        assert_eq!(rows, 0, "depth-capped turn must not persist a message row");
    }

    // Test 5: voice-channel session → 409 {"code":"wrong_channel"}, nothing
    // persisted.
    #[sqlx::test(migrations = "../eros-engine-store/migrations")]
    async fn async_409_when_session_is_voice_channel(pool: PgPool) {
        let user_id = Uuid::new_v4();
        let genome_id = seed_genome(&pool, "Aria").await;
        let instance_id = seed_instance(&pool, genome_id, user_id).await;
        let session_id: Uuid = sqlx::query_scalar(
            "INSERT INTO engine.chat_sessions (user_id, instance_id, channel) \
             VALUES ($1, $2, 'voice') RETURNING id",
        )
        .bind(user_id)
        .bind(instance_id)
        .fetch_one(&pool)
        .await
        .unwrap();

        let mut app = build_router(test_state(pool.clone()));
        let token = mint_test_jwt(user_id);
        let (status, body) = post_json(
            &mut app,
            &async_uri(session_id),
            &token,
            json!({"content":"typed","client_msg_id":"01JV000000000000000000004A"}),
        )
        .await;
        assert_eq!(status, StatusCode::CONFLICT, "body: {body}");
        assert_eq!(body["code"], "wrong_channel");

        let rows: i64 =
            sqlx::query_scalar("SELECT count(*) FROM engine.chat_messages WHERE session_id = $1")
                .bind(session_id)
                .fetch_one(&pool)
                .await
                .unwrap();
        assert_eq!(rows, 0, "a rejected async turn must not persist any row");
    }

